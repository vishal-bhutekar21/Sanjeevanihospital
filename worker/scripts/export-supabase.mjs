#!/usr/bin/env node
/**
 * Copy the hospital data from Supabase (PostgreSQL) into SQL for Cloudflare D1.
 *
 *   SUPABASE_DATABASE_URL="postgresql://..." node scripts/export-supabase.mjs
 *   npx wrangler d1 execute sanjeevani-db --remote --file=seed/supabase-import.sql
 *
 * The GitHub workflow "Worker: import data" runs both steps for you.
 *
 * - Ids are copied unchanged. Re-running is safe (INSERT OR REPLACE).
 * - doctors get `website_id` (e.g. "doc-bagal") by matching names with the
 *   website roster; doctor_schedules are re-keyed to that website id.
 * - Rows the Worker reads by tenant (settings, reviews, events, audit,
 *   appointments) get hospital_id = HOSPITAL_TENANT_ID.
 * - Short-lived booking data (booking_sessions, appointment_slots) is skipped.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';

const here = dirname(fileURLToPath(import.meta.url));
const url = process.env.SUPABASE_DATABASE_URL || process.env.DIRECT_URL || process.env.DATABASE_URL;
const tenant = process.env.HOSPITAL_TENANT_ID || 'hosp-sanjeevani-jalna';
const outFile = join(here, '..', 'seed', 'supabase-import.sql');

if (!url) {
  console.error('Set SUPABASE_DATABASE_URL (the Supabase "direct" connection string, port 5432).');
  process.exit(1);
}

// Website roster (id + name) from src/data/roster.ts
const rosterSrc = readFileSync(join(here, '..', 'src', 'data', 'roster.ts'), 'utf8');
const roster = [...rosterSrc.matchAll(/\{\s*id:\s*'([^']+)',\s*name:\s*'([^']+)'/g)].map((m) => ({ id: m[1], name: m[2] }));
const normName = (n) => String(n).toLowerCase().replace(/^dr\.?\s*/, '').replace(/\([^)]*\)/g, '').replace(/[^a-z]/g, '');
const websiteIdFor = (name) => {
  const want = normName(name);
  const hit = roster.find((r) => {
    const got = normName(r.name);
    return got === want || want.startsWith(got) || got.startsWith(want);
  });
  return hit?.id ?? null;
};

const sqlValue = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'boolean') return v ? '1' : '0';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL';
  if (v instanceof Date) return `'${v.toISOString()}'`;
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const dateOnly = (v) => (v instanceof Date ? v.toISOString().slice(0, 10) : v ? String(v).slice(0, 10) : null);

const client = new pg.Client({ connectionString: url, ssl: url.includes('localhost') ? false : { rejectUnauthorized: false } });
await client.connect();

const lines = ['-- Generated by scripts/export-supabase.mjs. Safe to run more than once.', 'PRAGMA defer_foreign_keys = ON;'];
const counts = {};
const tableExists = async (t) =>
  (await client.query(`SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = $1`, [t])).rowCount > 0;

/** rows → INSERT OR REPLACE with the given column list (rename map: d1Column -> value getter). */
function emit(table, rows, columns) {
  counts[table] = rows.length;
  for (const r of rows) {
    const cols = Object.keys(columns);
    lines.push(`INSERT OR REPLACE INTO ${table} (${cols.join(', ')}) VALUES (${cols.map((c) => sqlValue(columns[c](r))).join(', ')});`);
  }
}
const col = (name) => (r) => r[name];
const pick = (...names) => Object.fromEntries(names.map((n) => [n, col(n)]));

async function read(table) {
  if (!(await tableExists(table))) {
    console.warn(`- ${table}: not found in Supabase, skipped`);
    return [];
  }
  return (await client.query(`SELECT * FROM "${table}"`)).rows;
}

// hospitals, admins, departments, doctors: same ids
emit('hospitals', await read('hospitals'), pick('id', 'name', 'slug', 'tagline', 'address', 'city', 'state', 'pincode', 'phone', 'emergency_phone', 'email', 'established_year', 'latitude', 'longitude', 'is_active', 'created_at', 'updated_at'));
emit('hospital_admins', await read('hospital_admins'), pick('id', 'hospital_id', 'supabase_user_id', 'name', 'email', 'password_hash', 'role', 'is_active', 'created_at', 'updated_at'));
emit('departments', await read('departments'), pick('id', 'hospital_id', 'name_en', 'name_mr', 'slug', 'description_en', 'description_mr', 'icon', 'is_active', 'created_at', 'updated_at'));

const doctors = await read('doctors');
const usedWebsiteIds = new Set();
const doctorWebsiteId = new Map();
for (const d of doctors) {
  const w = websiteIdFor(d.name);
  if (w && !usedWebsiteIds.has(w)) {
    usedWebsiteIds.add(w);
    doctorWebsiteId.set(d.id, w);
  }
}
emit('doctors', doctors, {
  ...pick('id', 'hospital_id', 'department_id', 'name', 'designation', 'specialty', 'qualifications', 'experience_years', 'consultation_fee', 'photo_url', 'is_active', 'created_at', 'updated_at'),
  website_id: (r) => doctorWebsiteId.get(r.id) ?? null,
});

// OPD timings: re-key to website doctor ids
const schedules = (await read('doctor_schedules')).filter((s) => doctorWebsiteId.has(s.doctor_id));
emit('doctor_schedules', schedules, {
  ...pick('id', 'day_of_week', 'start_time', 'end_time', 'slot_duration_mins', 'is_active', 'created_at', 'updated_at'),
  doctor_id: (r) => doctorWebsiteId.get(r.doctor_id),
});
const scheduleIds = new Set(schedules.map((s) => s.id));
emit('schedule_breaks', (await read('schedule_breaks')).filter((b) => scheduleIds.has(b.doctor_schedule_id)), pick('id', 'doctor_schedule_id', 'break_start', 'break_end'));

const tenantId = () => tenant;
emit('hospital_settings', await read('hospital_settings'), { ...pick('id', 'key', 'value', 'created_at', 'updated_at'), hospital_id: tenantId });
emit('audit_logs', await read('audit_logs'), { ...pick('id', 'user_id', 'action', 'entity', 'entity_id', 'metadata', 'created_at'), hospital_id: tenantId });
emit('hospital_events', await read('hospital_events'), {
  ...pick('id', 'title', 'description', 'category', 'image_url', 'is_active', 'created_at', 'updated_at'),
  hospital_id: tenantId,
  event_date: (r) => dateOnly(r.event_date),
  status: (r) => (dateOnly(r.event_date) < new Date().toISOString().slice(0, 10) ? 'COMPLETED' : 'UPCOMING'),
});
emit('patient_reviews', await read('patient_reviews'), {
  ...pick('id', 'patient_name', 'department', 'rating', 'comment', 'source', 'status', 'created_at', 'updated_at'),
  hospital_id: tenantId,
});

// Appointments that were saved in Supabase (the old server mostly kept them in memory)
const doctorById = new Map(doctors.map((d) => [d.id, d]));
emit('appointments', await read('appointments'), {
  ...pick('id', 'appointment_code', 'department_id', 'patient_name', 'patient_age', 'patient_gender', 'patient_address', 'start_time', 'status', 'notes', 'created_at', 'updated_at'),
  hospital_id: tenantId,
  doctor_id: (r) => doctorWebsiteId.get(r.doctor_id) ?? r.doctor_id,
  doctor_name: (r) => doctorById.get(r.doctor_id)?.name ?? null,
  fee: (r) => doctorById.get(r.doctor_id)?.consultation_fee ?? 0,
  patient_phone: (r) => String(r.patient_phone || '').replace(/\D/g, '').slice(-10),
  appointment_date: (r) => dateOnly(r.appointment_date),
  payment_status: (r) => (r.payment_id ? 'PAID' : 'PENDING'),
});

await client.end();
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, lines.join('\n') + '\n');

console.log(`Wrote ${outFile}`);
for (const [t, n] of Object.entries(counts)) console.log(`  ${t}: ${n}`);
const unmatched = doctors.filter((d) => !doctorWebsiteId.has(d.id)).map((d) => d.name);
if (unmatched.length) console.log(`Doctors not matched to a website id (their OPD timings were not copied): ${unmatched.join(', ')}`);
